import {test} from 'node:test';
import assert from 'node:assert/strict';
import {diffLines,parseTime,parseSubtitles,shiftSubtitles,serializeSubtitles} from './core.mjs';
test('diff insertion deletion and unchanged lines',()=>{assert.deepEqual(diffLines('a\nb','a\nc').map(r=>r.kind),['same','removed','added']);});
test('diff handles empty input',()=>assert.equal(diffLines('','')[0].kind,'same'));
test('diff bounds memory',()=>assert.throws(()=>diffLines('\n'.repeat(1001),'x')));
test('diff malicious text remains text',()=>assert.equal(diffLines('','<script>x</script>')[1].text,'<script>x</script>'));
test('parse milliseconds',()=>assert.equal(parseTime('01:02:03,045'),3723045));
test('invalid time rejected',()=>assert.throws(()=>parseTime('00:61:00,000')));
const source='1\r\n00:00:01,000 --> 00:00:02,500\r\n안녕\r\n두 줄';
test('SRT CRLF and multiline',()=>assert.deepEqual(parseSubtitles(source),[{start:1000,end:2500,text:'안녕\n두 줄'}]));
test('VTT conversion roundtrip',()=>{const cues=parseSubtitles(source);assert.deepEqual(parseSubtitles(serializeSubtitles(cues,'vtt')),cues);});
test('VTT minute timestamps',()=>assert.equal(parseSubtitles('WEBVTT\n\n00:01.000 --> 00:02.000\nx')[0].start,1000));
test('positive and fractional shift',()=>assert.equal(shiftSubtitles(parseSubtitles(source),0.125)[0].start,1125));
test('negative invalid shift refuses data loss',()=>assert.throws(()=>shiftSubtitles(parseSubtitles(source),-2)));
test('NaN shift rejected',()=>assert.throws(()=>shiftSubtitles([],NaN)));
test('settings rejected explicitly',()=>assert.throws(()=>parseSubtitles('WEBVTT\n\n00:01.000 --> 00:02.000 align:start\nx')));
test('formatting rejected explicitly',()=>assert.throws(()=>parseSubtitles(source.replace('안녕','<b>안녕</b>'))));
test('reversed time rejected',()=>assert.throws(()=>parseSubtitles(source.replace('00:00:02,500','00:00:00,500'))));
test('VTT metadata rejected',()=>assert.throws(()=>parseSubtitles('WEBVTT\nX-TIMESTAMP-MAP=a\n\n00:01.000 --> 00:02.000\nx')));
test('unknown formats rejected',()=>assert.throws(()=>serializeSubtitles([],'ass')));
test('huge hours rejected',()=>assert.throws(()=>parseTime('999999999999999999999999:00:00.000')));
test('shift cannot overflow time limit',()=>assert.throws(()=>shiftSubtitles([{start:359999000,end:359999999,text:'x'}],1)));
